"""Tests for diff_size.py's product-code filter (slice 03 of specs/diff-size/).

Run: python3 -m unittest discover -s skills/slice-spec/scripts
"""
from __future__ import annotations

import os
import sys
import tempfile
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import diff_size as d  # noqa: E402
from test_diff_size import BLOCK, OTHER, Repo, lines, totals  # noqa: E402


class FilterTest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.repo = Repo(Path(self.tmp.name))
        self.old_env = dict(os.environ)
        os.environ.update(GIT_CONFIG_GLOBAL=os.devnull, GIT_CONFIG_NOSYSTEM="1")
        self.repo.write("src/keep.py", lines(OTHER))
        self.base = self.repo.commit("base")

    def tearDown(self):
        os.environ.clear()
        os.environ.update(self.old_env)
        self.tmp.cleanup()

    def product(self) -> tuple[tuple[int, int, int, int], dict[str, int], list[str]]:
        head = self.repo.commit()
        files, filtered = d.count_product(self.repo.root, d.parent(self.repo.root, head), head)
        return totals(files), filtered.skipped, sorted(f.path for f in files)

    def test_each_skip_rule_contributes_nothing(self):
        self.repo.write("package-lock.json", '{"lockfileVersion": 3}\n')
        self.repo.write("dist/bundle.js", lines(BLOCK))
        self.repo.write("pkg/package.json", "{}\n")
        self.repo.write("pkg/build/out.js", lines(BLOCK))
        self.repo.write("web/node_modules/lib/index.js", lines(BLOCK))
        self.repo.write(".gitattributes", "gen/** linguist-generated\n")
        self.repo.write("gen/client.py", lines(BLOCK))
        self.repo.write("src/schema_pb2.py", "# Generated by the protocol buffer compiler.  DO NOT EDIT!\n" + lines(BLOCK))
        self.repo.write("src/blob.py", "x = 1\n\0\1\2\n")
        self.repo.write("docs/guide.md", lines(BLOCK))
        self.repo.write("src/real.py", lines(BLOCK))
        counts, skipped, paths = self.product()
        self.assertEqual(paths, ["src/real.py"])
        self.assertEqual(counts, (5, 0, 0, 0))
        self.assertEqual(skipped, {"lockfile": 1, "vendored-or-build": 3, "marked-generated": 1,
                                   "generated-header": 1, "binary": 1, "not-code": 3})

    def test_build_folder_below_a_non_package_folder_still_counts(self):
        self.repo.write("tools/build/make.py", lines(BLOCK))
        counts, skipped, _ = self.product()
        self.assertEqual(counts, (5, 0, 0, 0))
        self.assertEqual(skipped, {})

    def test_build_output_cannot_supply_moves(self):
        self.repo.write("dist/a.js", lines(BLOCK))
        self.repo.commit()
        self.repo.run("rm", "-q", "dist/a.js")
        self.repo.write("src/a.py", lines(BLOCK))
        counts, skipped, _ = self.product()
        self.assertEqual(counts, (5, 0, 0, 0))
        # git pairs the two as a rename; its build-output side is left out, so nothing skips.
        self.assertEqual(skipped, {})

    def test_rename_out_of_build_output_is_new_code(self):
        self.repo.write("dist/a.py", lines(BLOCK))
        self.repo.commit()
        self.repo.run("mv", "dist/a.py", "src/a.py")
        counts, skipped, paths = self.product()
        self.assertEqual(counts, (5, 0, 0, 0))
        self.assertEqual(paths, ["src/a.py"])

    def test_deleted_lines_are_judged_against_the_parent_tree(self):
        self.repo.write(".gitattributes", "old/** linguist-generated\n")
        self.repo.write("old/gen.py", lines(BLOCK))
        self.repo.write("src/gone.py", lines(BLOCK))
        self.repo.commit()
        # The head drops the attribute file too; the parent's attributes still apply.
        self.repo.run("rm", "-q", ".gitattributes", "old/gen.py", "src/gone.py")
        counts, skipped, _ = self.product()
        self.assertEqual(counts, (0, 0, 5, 0))
        self.assertEqual(skipped, {"marked-generated": 1, "not-code": 1})

    def test_symlinks_are_not_files(self):
        os.symlink("keep.py", self.repo.root / "src" / "link.py")
        counts, skipped, _ = self.product()
        self.assertEqual(counts, (0, 0, 0, 0))
        self.assertEqual(skipped, {"not-a-file": 1})

    def test_odd_names_pass_through_literally(self):
        self.repo.write("src/[abc]*.py", lines(BLOCK))
        self.repo.write("src/a.py", lines(OTHER, BLOCK))
        counts, _, paths = self.product()
        self.assertEqual(paths, ["src/[abc]*.py", "src/a.py"])
        self.assertEqual(counts[0] + counts[1], 14)

    # Each side is judged on its own (Check 3): a skipped side adds no lines.
    def test_attributes_added_in_the_same_commit_apply(self):
        self.repo.write("gen/x.py", lines(OTHER))
        self.repo.commit()
        self.repo.write(".gitattributes", "gen/** linguist-generated\n")
        self.repo.write("gen/x.py", lines(OTHER, BLOCK))
        counts, _, _ = self.product()
        self.assertEqual(counts[0], 0)

    def test_package_marker_added_in_the_same_commit_applies(self):
        self.repo.write("pkg/build/out.js", lines(OTHER))
        self.repo.commit()
        self.repo.write("pkg/package.json", "{}\n")
        self.repo.write("pkg/build/out.js", lines(OTHER, BLOCK))
        counts, _, _ = self.product()
        self.assertEqual(counts[0], 0)

    def test_generated_header_added_in_the_same_commit_applies(self):
        self.repo.write("src/a.py", lines(OTHER))
        self.repo.commit()
        self.repo.write("src/a.py", "# @generated by protoc\n" + lines(OTHER, BLOCK))
        counts, _, _ = self.product()
        self.assertEqual(counts[0], 0)

    def test_a_file_that_turns_binary_counts_as_deleted(self):
        self.repo.write("src/a.py", lines(BLOCK))
        self.repo.commit()
        self.repo.write("src/a.py", "\0\1\2 binary now\n")
        self.assertEqual(self.product()[0], (0, 0, 5, 0))

    def test_a_file_that_turns_into_a_symlink_counts_as_deleted(self):
        self.repo.write("src/a.py", lines(BLOCK))
        self.repo.commit()
        (self.repo.root / "src" / "a.py").unlink()
        os.symlink("keep.py", self.repo.root / "src" / "a.py")
        self.assertEqual(self.product()[0], (0, 0, 5, 0))

    def test_a_skipped_old_side_supplies_no_moves(self):
        self.repo.write(".gitattributes", "gen/** linguist-generated\n")
        self.repo.write("gen/x.py", lines(BLOCK))
        self.repo.commit()
        self.repo.run("rm", "-q", ".gitattributes")
        self.repo.write("gen/x.py", lines(OTHER))
        self.repo.write("src/y.py", lines(BLOCK))
        counts, _, _ = self.product()
        self.assertEqual(counts[1], 0)
        self.assertGreaterEqual(counts[0], 5)

    def test_runs_from_a_subfolder(self):
        self.repo.write("src/a.py", lines(BLOCK))
        head = self.repo.commit()
        files, _ = d.count_product(self.repo.root / "src", d.parent(self.repo.root, head), head)
        self.assertEqual(totals(files), (5, 0, 0, 0))

    def test_nothing_is_written_to_the_repo(self):
        self.repo.write("dist/a.js", lines(BLOCK))
        self.repo.write("src/a.py", lines(BLOCK))
        head = self.repo.commit()
        before = self.repo.run("count-objects", "-v")
        d.count_product(self.repo.root, d.parent(self.repo.root, head), head)
        self.assertEqual(self.repo.run("count-objects", "-v"), before)

    def test_nothing_product_means_no_diff(self):
        self.repo.write("README.md", "hello\n")
        counts, skipped, paths = self.product()
        self.assertEqual((counts, paths), ((0, 0, 0, 0), []))
        self.assertEqual(skipped, {"not-code": 1})


if __name__ == "__main__":
    unittest.main()
