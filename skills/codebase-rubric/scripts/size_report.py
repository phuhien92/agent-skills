#!/usr/bin/env python3
"""Report source files over the size tiers: target 500, soft 800, hard 1000 lines.

Usage: size_report.py <repo> [--json]

Counts raw newlines in every file git tracks (or every file under <repo> when
it isn't a git repo). Skips lockfiles, vendored and build folders, files marked
linguist-generated or linguist-vendored in .gitattributes, files whose first
lines say they are generated, and binary files. Prints files over 500 lines,
largest first, then skip counts by reason. Output is deterministic.
Standard library only. Exits 2 with a reason if <repo> is not a directory.
"""
from __future__ import annotations

import fnmatch
import json
import os
import subprocess
import sys
from pathlib import Path

TARGET, SOFT, HARD = 500, 800, 1000

LOCKFILES = {
    "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "bun.lockb", "bun.lock",
    "Cargo.lock", "poetry.lock", "Pipfile.lock", "uv.lock", "composer.lock",
    "Gemfile.lock", "go.sum", "mix.lock", "pubspec.lock", "Podfile.lock",
    "flake.lock", "packages.lock.json",
}
SKIP_DIRS = {"vendor", "node_modules", "dist", "build", "third_party", ".git"}
GENERATED_MARKERS = (
    "@generated", "do not edit", "code generated by", "autogenerated",
    "auto-generated", "this file is generated", "automatically generated",
)
HEADER_LINES = 5
SNIFF_BYTES = 8192


def tier(lines: int) -> str | None:
    if lines > HARD:
        return "hard"
    if lines > SOFT:
        return "soft"
    if lines > TARGET:
        return "target"
    return None


def list_files(repo: Path) -> list[str]:
    try:
        out = subprocess.run(
            ["git", "-C", str(repo), "-c", "core.quotePath=false", "ls-files", "-z"],
            capture_output=True, check=True,
        ).stdout
        return sorted(p for p in out.decode("utf-8", "surrogateescape").split("\0") if p)
    except (subprocess.CalledProcessError, FileNotFoundError):
        found = []
        for root, dirs, files in os.walk(repo):
            dirs[:] = sorted(d for d in dirs if d != ".git")
            for name in files:
                found.append(str((Path(root) / name).relative_to(repo)))
        return sorted(found)


def gitattr_patterns(repo: Path) -> list[str]:
    """Patterns marked linguist-generated or linguist-vendored in the root .gitattributes."""
    path = repo / ".gitattributes"
    if not path.is_file():
        return []
    patterns = []
    for raw in path.read_text(encoding="utf-8", errors="replace").splitlines():
        parts = raw.split()
        if len(parts) < 2 or parts[0].startswith("#"):
            continue
        attrs = parts[1:]
        if any(a in ("linguist-generated", "linguist-generated=true",
                     "linguist-vendored", "linguist-vendored=true") for a in attrs):
            patterns.append(parts[0])
    return patterns


def matches_gitattr(rel: str, patterns: list[str]) -> bool:
    for pat in patterns:
        p = pat.lstrip("/")
        if p.endswith("/"):
            p += "**"
        if fnmatch.fnmatch(rel, p) or ("/" not in p and fnmatch.fnmatch(Path(rel).name, p)):
            return True
        if p.endswith("/**") and rel.startswith(p[:-3] + "/"):
            return True
    return False


def skip_reason(rel: str, head: bytes, patterns: list[str]) -> str | None:
    parts = Path(rel).parts
    if Path(rel).name in LOCKFILES:
        return "lockfile"
    if any(p in SKIP_DIRS for p in parts[:-1]):
        return "vendored or build folder"
    if matches_gitattr(rel, patterns):
        return "marked generated or vendored"
    if b"\0" in head:
        return "binary"
    top = b"\n".join(head.splitlines()[:HEADER_LINES]).decode("utf-8", "replace").lower()
    if any(m in top for m in GENERATED_MARKERS):
        return "generated header"
    return None


def report(repo: Path) -> dict:
    patterns = gitattr_patterns(repo)
    rows, skipped = [], {}
    for rel in list_files(repo):
        path = repo / rel
        if not path.is_file() or path.is_symlink():
            continue
        with path.open("rb") as fh:
            head = fh.read(SNIFF_BYTES)
            reason = skip_reason(rel, head, patterns)
            if reason:
                skipped[reason] = skipped.get(reason, 0) + 1
                continue
            lines = head.count(b"\n")
            for chunk in iter(lambda: fh.read(1 << 16), b""):
                lines += chunk.count(b"\n")
        t = tier(lines)
        if t:
            rows.append({"path": rel, "lines": lines, "tier": t})
    rows.sort(key=lambda r: (-r["lines"], r["path"]))
    return {"tiers": {"target": TARGET, "soft": SOFT, "hard": HARD},
            "files": rows, "skipped": dict(sorted(skipped.items()))}


LABEL = {"hard": f"over hard ({HARD})", "soft": f"over soft ({SOFT})", "target": f"over target ({TARGET})"}


def as_text(data: dict) -> str:
    out = ["| File | Lines | Tier |", "|---|---|---|"]
    out += [f"| `{r['path']}` | {r['lines']} | {LABEL[r['tier']]} |" for r in data["files"]]
    if not data["files"]:
        out.append(f"| (none over {TARGET}) | | |")
    out.append("")
    skipped = ", ".join(f"{k}: {v}" for k, v in data["skipped"].items()) or "none"
    out.append(f"Skipped: {skipped}")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    args = [a for a in argv if a != "--json"]
    if len(args) != 1:
        print(__doc__.strip().splitlines()[2], file=sys.stderr)
        return 2
    repo = Path(args[0])
    if not repo.is_dir():
        print(f"size_report: {repo} is not a directory", file=sys.stderr)
        return 2
    data = report(repo.resolve())
    print(json.dumps(data, indent=2) if "--json" in argv else as_text(data))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
