#!/usr/bin/env python3
"""Report source files over the size tiers: target 500, soft 800, hard 1000 lines.

Usage: size_report.py <repo> [--json]

Counts raw newlines in every code file git tracks (or every file under <repo>
when it isn't a git repo). Skips non-code files (docs, data, images; styles and markup count as code), lockfiles,
node_modules/ and vendor/ at any depth, dist/ and build/ at the repo root or a
package root, files git marks linguist-generated or linguist-vendored, files
whose first lines say they are generated, and binary files. Every listed path
is either in the table or counted under a skip reason. Prints files over 500 lines,
largest first, then skip counts by reason. Output is deterministic.
Standard library only. Exits 2 with a reason if <repo> is not a directory.
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

TARGET, SOFT, HARD = 500, 800, 1000

LOCKFILES = {
    "package-lock.json", "yarn.lock", "pnpm-lock.yaml", "bun.lockb", "bun.lock",
    "Cargo.lock", "poetry.lock", "Pipfile.lock", "uv.lock", "composer.lock",
    "Gemfile.lock", "go.sum", "mix.lock", "pubspec.lock", "Podfile.lock",
    "flake.lock", "packages.lock.json",
}
ANY_DEPTH_DIRS = {"node_modules", "vendor", ".git"}
ROOT_BUILD_DIRS = {"dist", "build"}
PACKAGE_MARKERS = ("package.json", "pyproject.toml", "setup.py", "Cargo.toml",
                   "go.mod", "pom.xml", "build.gradle", "build.gradle.kts",
                   "composer.json", "Gemfile", "mix.exs", "pubspec.yaml")
CODE_EXTENSIONS = {
    ".py", ".pyi", ".js", ".jsx", ".mjs", ".cjs", ".ts", ".tsx", ".mts", ".cts",
    ".go", ".rs", ".java", ".kt", ".kts", ".scala", ".swift", ".m", ".mm",
    ".c", ".h", ".cc", ".cpp", ".cxx", ".hpp", ".hh", ".cs", ".fs", ".rb",
    ".php", ".ex", ".exs", ".erl", ".clj", ".cljs", ".dart", ".lua", ".pl",
    ".pm", ".r", ".jl", ".hs", ".ml", ".mli", ".elm", ".vue", ".svelte",
    ".astro", ".sh", ".bash", ".zsh", ".fish", ".ps1", ".sql", ".graphql",
    ".proto", ".zig", ".nim", ".v", ".sv", ".vhd", ".tf", ".hcl",
    ".css", ".scss", ".sass", ".less", ".html", ".htm", ".mdx",
}
CODE_NAMES = {"Makefile", "Dockerfile", "Rakefile", "Justfile"}
# Stable keys for --json; phrases for the text table.
SKIP_LABELS = {
    "not-a-file": "symlink or not a file",
    "not-code": "not a code file",
    "lockfile": "lockfile",
    "vendored-or-build": "vendored or build folder",
    "marked-generated": "marked generated or vendored",
    "binary": "binary",
    "generated-header": "generated header",
}
GENERATED_MARKERS = (
    "@generated", "do not edit", "code generated by", "autogenerated",
    "auto-generated", "this file is generated", "automatically generated",
)
HEADER_LINES = 5
SNIFF_BYTES = 8192


def tier(lines: int) -> str | None:
    if lines > HARD:
        return "hard"
    if lines > SOFT:
        return "soft"
    if lines > TARGET:
        return "target"
    return None


def list_files(repo: Path) -> list[str]:
    try:
        out = subprocess.run(
            ["git", "-C", str(repo), "-c", "core.quotePath=false", "ls-files", "-z"],
            capture_output=True, check=True,
        ).stdout
        return sorted(p for p in out.decode("utf-8", "surrogateescape").split("\0") if p)
    except (subprocess.CalledProcessError, FileNotFoundError):
        found = []
        for root, dirs, files in os.walk(repo):
            dirs[:] = sorted(d for d in dirs if d != ".git")
            for name in files:
                found.append(str((Path(root) / name).relative_to(repo)))
        return sorted(found)


def marked_paths(repo: Path, paths: list[str]) -> set[str]:
    """Paths git reports as linguist-generated or linguist-vendored.

    Asks git itself (`git check-attr`), so nested .gitattributes files, negations,
    and git's own pattern rules all apply. Outside git, nothing is marked.
    """
    if not paths:
        return set()
    try:
        out = subprocess.run(
            ["git", "-C", str(repo), "check-attr", "-z", "--stdin",
             "linguist-generated", "linguist-vendored"],
            input="\0".join(paths).encode("utf-8", "surrogateescape"),
            capture_output=True, check=True,
        ).stdout.decode("utf-8", "surrogateescape").split("\0")
    except (subprocess.CalledProcessError, FileNotFoundError):
        return set()
    marked = set()
    for i in range(0, len(out) - 2, 3):
        path, _attr, value = out[i:i + 3]
        if value in ("set", "true"):
            marked.add(path)
    return marked


def is_code(rel: str) -> bool:
    p = Path(rel)
    return p.suffix.lower() in CODE_EXTENSIONS or p.name in CODE_NAMES


def in_build_dir(repo: Path, rel: str) -> bool:
    """dist/ or build/ directly under the repo root or a package root."""
    parts = Path(rel).parts[:-1]
    for i, part in enumerate(parts):
        if part in ANY_DEPTH_DIRS:
            return True
        if part in ROOT_BUILD_DIRS:
            parent = repo.joinpath(*parts[:i])
            if i == 0 or any((parent / m).is_file() for m in PACKAGE_MARKERS):
                return True
    return False


def skip_reason(repo: Path, rel: str, head: bytes, marked: set[str]) -> str | None:
    if Path(rel).name in LOCKFILES:
        return "lockfile"
    if in_build_dir(repo, rel):
        return "vendored-or-build"
    if not is_code(rel):
        return "not-code"
    if rel in marked:
        return "marked-generated"
    if b"\0" in head:
        return "binary"
    top = b"\n".join(head.splitlines()[:HEADER_LINES]).decode("utf-8", "replace").lower()
    if any(m in top for m in GENERATED_MARKERS):
        return "generated-header"
    return None


def report(repo: Path) -> dict:
    paths = list_files(repo)
    marked = marked_paths(repo, paths)
    rows, skipped = [], {}
    for rel in paths:
        path = repo / rel
        if path.is_symlink() or not path.is_file():
            skipped["not-a-file"] = skipped.get("not-a-file", 0) + 1
            continue
        with path.open("rb") as fh:
            head = fh.read(SNIFF_BYTES)
            reason = skip_reason(repo, rel, head, marked)
            if reason:
                skipped[reason] = skipped.get(reason, 0) + 1
                continue
            lines = head.count(b"\n")
            for chunk in iter(lambda: fh.read(1 << 16), b""):
                lines += chunk.count(b"\n")
        t = tier(lines)
        if t:
            rows.append({"path": rel, "lines": lines, "tier": t})
    rows.sort(key=lambda r: (-r["lines"], r["path"]))
    return {"tiers": {"target": TARGET, "soft": SOFT, "hard": HARD},
            "files": rows, "skipped": dict(sorted(skipped.items()))}


LABEL = {"hard": f"over hard ({HARD})", "soft": f"over soft ({SOFT})", "target": f"over target ({TARGET})"}


def as_text(data: dict) -> str:
    out = ["| File | Lines | Tier |", "|---|---|---|"]
    out += [f"| `{r['path']}` | {r['lines']} | {LABEL[r['tier']]} |" for r in data["files"]]
    if not data["files"]:
        out.append(f"| (none over {TARGET}) | | |")
    out.append("")
    skipped = ", ".join(f"{SKIP_LABELS[k]}: {v}" for k, v in data["skipped"].items()) or "none"
    out.append(f"Skipped: {skipped}")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    args = [a for a in argv if a != "--json"]
    if len(args) != 1:
        print(__doc__.strip().splitlines()[2], file=sys.stderr)
        return 2
    repo = Path(args[0])
    if not repo.is_dir():
        print(f"size_report: {repo} is not a directory", file=sys.stderr)
        return 2
    data = report(repo.resolve())
    print(json.dumps(data, indent=2) if "--json" in argv else as_text(data))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
