"""Tests for size_report.py. Run: python3 -m unittest discover -s skills/codebase-rubric/scripts"""
from __future__ import annotations

import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import size_report  # noqa: E402

SCRIPT = HERE / "size_report.py"


def lines(n: int, first: str = "x") -> str:
    return "".join(f"{first if i == 0 else 'x'}\n" for i in range(n))


class SizeReportTest(unittest.TestCase):
    def setUp(self) -> None:
        self.tmp = tempfile.TemporaryDirectory()
        self.repo = Path(self.tmp.name)
        files = {
            "a499.py": lines(499),
            "b501.py": lines(501),
            "c801.ts": lines(801),
            "src/d1001.go": lines(1001),
            "package-lock.json": lines(3000),
            "node_modules/x.js": lines(2000),
            "dist/cli.js": lines(1500),
            "gen/schema.ts": lines(900),
            "api_pb.py": lines(1200, first="# Code generated by protoc. DO NOT EDIT."),
            "e1000.py": lines(1000),
            "f800.py": lines(800),
        }
        for rel, text in files.items():
            p = self.repo / rel
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text)
        (self.repo / "logo.png").write_bytes(b"\x89PNG\r\n\x1a\n\0\0" + b"\n" * 2000)
        (self.repo / ".gitattributes").write_text("gen/** linguist-generated\n")
        subprocess.run(["git", "init", "-q", str(self.repo)], check=True)
        subprocess.run(["git", "-C", str(self.repo), "add", "-A", "-f"], check=True)

    def tearDown(self) -> None:
        self.tmp.cleanup()

    def test_tiers(self) -> None:
        data = size_report.report(self.repo)
        got = {r["path"]: (r["lines"], r["tier"]) for r in data["files"]}
        self.assertEqual(got, {
            "src/d1001.go": (1001, "hard"),
            "e1000.py": (1000, "soft"),
            "c801.ts": (801, "soft"),
            "f800.py": (800, "target"),
            "b501.py": (501, "target"),
        })
        self.assertEqual([r["path"] for r in data["files"]][0], "src/d1001.go")

    def test_skips(self) -> None:
        data = size_report.report(self.repo)
        self.assertEqual(data["skipped"], {
            "binary": 1,
            "generated header": 1,
            "lockfile": 1,
            "marked generated or vendored": 1,
            "vendored or build folder": 2,
        })

    def test_deterministic(self) -> None:
        run = lambda: subprocess.run([sys.executable, str(SCRIPT), str(self.repo)],
                                     capture_output=True, check=True).stdout
        first = run()
        self.assertEqual(first, run())
        self.assertIn(b"`src/d1001.go` | 1001 | over hard (1000)", first)

    def test_not_a_directory(self) -> None:
        res = subprocess.run([sys.executable, str(SCRIPT), str(self.repo / "nope")],
                             capture_output=True)
        self.assertEqual(res.returncode, 2)
        self.assertIn(b"is not a directory", res.stderr)

    def test_works_without_git(self) -> None:
        with tempfile.TemporaryDirectory() as d:
            (Path(d) / "big.py").write_text(lines(600))
            data = size_report.report(Path(d))
            self.assertEqual(data["files"], [{"path": "big.py", "lines": 600, "tier": "target"}])


if __name__ == "__main__":
    unittest.main()
